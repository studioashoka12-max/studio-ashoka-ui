"""Regenerate responsive WebP assets: python3 scripts/optimize_images.py (Pillow required)."""
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
assets = root / 'src/assets'
out = assets / 'optimized'
out.mkdir(exist_ok=True)
sources = {
 'logo': 'L.png', 'hero': 'KIDS BED 4.jpg', 'bedroom': 'MR(3).jpg',
 'kitchen': 'KITCHEN_8 - Photo(1).jpg', 'landscapeLawn': 'op2_24 - Photo.jpg',
 'landscapePlan': 'op2_5 - Photo-1.jpg', 'landscapeView': 'op2_8 - Photo.jpg',
 'landscapePath': 'op2_9 - Photo.jpg', 'drawing': 'IMG_1424.jpg',
 'cafe': 'IMG-20250519-WA0017.jpg', 'floralCafe': 'IMG-20250519-WA0037.jpg',
 'livingOne': 'MR. MANDLIK LIVING ROOM 1.jpg', 'livingTwo': 'MR. MANDLIK LIVING ROOM 2.jpg',
 'livingRoom': '1_2 - Photo_3 - Photo.jpg',
}
imports, entries = [], []
original_bytes = largest_bytes = 0
for name, filename in sources.items():
    source = assets / filename
    original_bytes += source.stat().st_size
    with Image.open(source) as raw:
        im = ImageOps.exif_transpose(raw).convert('RGBA' if name == 'logo' else 'RGB')
        widths = [160, 320, 640] if name == 'logo' else [480, 800, 1200, 1600, 2400]
        widths = sorted(set(min(w, im.width) for w in widths))
        variants = []
        for width in widths:
            height = round(im.height * width / im.width)
            dest = out / f'{name}-{width}.webp'
            im.resize((width, height), Image.Resampling.LANCZOS).save(dest, 'WEBP', quality=85 if name == 'drawing' else 80, method=6)
            symbol = f'{name}{width}'
            imports.append(f'import {symbol} from "./{dest.name}";')
            variants.append((width, symbol))
        largest_bytes += dest.stat().st_size
        default = next((s for w,s in variants if w >= 800), variants[-1][1])
        srcset = ', '.join('${' + s + '} ' + str(w) + 'w' for w,s in variants)
        entries.append(f'export const {name} = {{ src: {default}, srcSet: `{srcset}`, width: {im.width}, height: {im.height} }};')
(out / 'images.js').write_text('// Generated by scripts/optimize_images.py. Do not edit by hand.\n' + '\n'.join(imports + [''] + entries) + '\n')
print(f'Original referenced assets: {original_bytes / 1024 / 1024:.2f} MiB')
print(f'Largest WebP variant per asset: {largest_bytes / 1024 / 1024:.2f} MiB ({100*(1-largest_bytes/original_bytes):.1f}% smaller)')
